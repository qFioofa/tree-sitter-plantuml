#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

LANG_NAME="plantuml"
EXTENSIONS=(puml iuml plantuml wsd pu)

ACTION="install"
SITE=""
while [ $# -gt 0 ]; do
	case "$1" in
	--uninstall) ACTION="uninstall" ;;
	--prefix)
		SITE="${2:-}"
		shift
		;;
	-h | --help)
		sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	*)
		echo "unknown argument: $1" >&2
		exit 2
		;;
	esac
	shift
done

if [ -z "$SITE" ]; then
	data_home="${XDG_DATA_HOME:-$HOME/.local/share}"
	SITE="$data_home/nvim/site"
fi

PARSER_DST="$SITE/parser/$LANG_NAME.so"
QUERY_DST="$SITE/queries/$LANG_NAME"
FTDETECT_DST="$SITE/ftdetect/$LANG_NAME.lua"
FTPLUGIN_DST="$SITE/after/ftplugin/$LANG_NAME.lua"

if [ "$ACTION" = "uninstall" ]; then
	rm -fv "$PARSER_DST" "$FTDETECT_DST" "$FTPLUGIN_DST"
	rm -rfv "$QUERY_DST"
	echo "Uninstalled $LANG_NAME from $SITE"
	exit 0
fi

if [ ! -f "$ROOT_DIR/src/parser.c" ]; then
	echo "error: src/parser.c not found — run 'tree-sitter generate' first." >&2
	exit 1
fi

CC="${CC:-cc}"
if ! command -v "$CC" >/dev/null 2>&1; then
	echo "error: C compiler '$CC' not found (set \$CC)." >&2
	exit 1
fi

tmp_so="$(mktemp -d)/$LANG_NAME.so"
sources=("$ROOT_DIR/src/parser.c")
[ -f "$ROOT_DIR/src/scanner.c" ] && sources+=("$ROOT_DIR/src/scanner.c")

echo "Building parser with $CC ..."
"$CC" -shared -fPIC -Os \
	-I "$ROOT_DIR/src" \
	-o "$tmp_so" \
	"${sources[@]}"

mkdir -p "$(dirname "$PARSER_DST")" "$QUERY_DST" \
	"$(dirname "$FTDETECT_DST")" "$(dirname "$FTPLUGIN_DST")"

install -m 0644 "$tmp_so" "$PARSER_DST"
echo "  -> $PARSER_DST"

for q in highlights injections locals tags folds indents textobjects context rainbow; do
	src="$ROOT_DIR/queries/$q.scm"
	[ -f "$src" ] && install -m 0644 "$src" "$QUERY_DST/$q.scm" && echo "  -> $QUERY_DST/$q.scm"
done

{
	echo "-- Generated by tree-sitter-plantuml scripts/nvim_deploy.sh"
	echo "vim.filetype.add({"
	echo "  extension = {"
	for ext in "${EXTENSIONS[@]}"; do
		echo "    $ext = \"$LANG_NAME\","
	done
	echo "  },"
	echo "})"
} >"$FTDETECT_DST"
echo "  -> $FTDETECT_DST"

# after/ftplugin: start the built-in treesitter highlighter for this buffer.
{
	echo "-- Generated by tree-sitter-plantuml scripts/nvim_deploy.sh"
	echo "pcall(vim.treesitter.start)"
	echo "vim.bo.commentstring = \"' %s\""
} >"$FTPLUGIN_DST"
echo "  -> $FTPLUGIN_DST"

cat <<EOF

Done. Installed $LANG_NAME into:
  $SITE

Open a .puml file in Neovim — highlighting starts automatically.
To verify:   nvim -c 'set ft?' -c 'lua print(vim.treesitter.highlighter.active[0] ~= nil)' file.puml
To remove:   scripts/nvim_deploy.sh --uninstall
EOF
